"""Opt-in five-well demo field assembled from the project's own datasets. It lives in its own field and can be removed."""
import json
import numpy as np
from common import ROOT
import store
from store import UserError

FIELD = "Demo field"
SOURCE = "demo (project datasets)"
# True connectivity used to generate the demo producers (rows ESP1, GL1, GL2; columns I1, I2).
TRUE_GAINS = np.array([[0.55, 0.15], [0.30, 0.45], [0.15, 0.40]])
TRUE_TAU = np.array([[25.0, 70.0], [45.0, 30.0], [90.0, 40.0]])


CODES = ("DEMO-I1", "DEMO-I2", "DEMO-ESP1", "DEMO-GL1", "DEMO-GL2")


def create(db):
    """Build the demo field. Loading it again resets it: the old demo field (and any well still carrying a demo ID)
    is deleted first. Wells in other fields are never touched; a demo well whose short name is already taken there
    is named by its demo ID instead (e.g. DEMO-I1)."""
    import pandas as pd
    remove(db)
    with db:
        for r in db.execute("SELECT id FROM wells WHERE code IN (%s)" % ",".join("?" * len(CODES)), CODES).fetchall():
            for table in ("results", "versions"):
                db.execute(f"DELETE FROM {table} WHERE well_id=?", (r["id"],))
            db.execute("DELETE FROM wells WHERE id=?", (r["id"],))
    note = ("Demo well assembled from project test datasets (pywaterflood, failure_1, failure_2, pinn, gas_pinc). Not field data. "
            "Producer rates are generated by a CRM with true f(I1,I2): ESP1 0.55/0.15, GL1 0.30/0.45, GL2 0.15/0.40.")
    wells = {}
    # code, short name, type, map position (m), settings
    spec = [("DEMO-I1", "I1", "injector", (1000, 1100), {}), ("DEMO-I2", "I2", "injector", (4300, 1300), {}),
            ("DEMO-ESP1", "ESP1", "esp", (2600, 2900), dict(current_hz=50, env_min_hz=40, env_max_hz=60)),
            # GL1 matches gas_pinc well 1, so its flow meter runs the gas_pinc networks; GL2 differs and uses the gas_pinc equations.
            ("DEMO-GL1", "GL1", "gas_lift", (1300, 4300), dict(current_gas_sm3d=160000, env_min_gas=0, env_max_gas=240000, glr_mass=0)),
            ("DEMO-GL2", "GL2", "gas_lift", (4000, 4100), dict(current_gas_sm3d=150000, env_min_gas=0, env_max_gas=250000, reservoir_bar=165,
                                                              pi_m3d_bar=24.1, tubing_depth_m=2700, tubing_id_m=0.130, glr_mass=0.02))]
    for code, short, kind, (x, y), settings in spec:
        name = code if store.find_well(db, short) is not None else short
        wells[short] = store.create_well(db, dict(code=code, name=name, type=kind, field=FIELD, notes=note, settings=settings,
                                                  easting=x, northing=y))["id"]
    # Injection is the real pywaterflood test history for two injectors. Producer history is generated from it by a CRM
    # with known connectivity plus 3% noise, so a history match can be checked against the true f_ij and tau_ij.
    from pywaterflood import CRM
    data = ROOT / "pywaterflood/testing/data"
    t = np.loadtxt(data / "time.csv")
    inj = np.loadtxt(data / "injection.csv", delimiter=",")[:, :2]
    connections = dict(gains=TRUE_GAINS, tau=TRUE_TAU, gains_producer=np.ones(3), tau_producer=np.array([400.0, 300.0, 500.0]))
    q = CRM(primary=True, tau_selection="per-pair").predict(injection=inj, time=t, connections=connections,
                                                           production=np.array([[300.0, 250.0, 200.0]]))
    q = q * (1 + 0.03 * np.random.default_rng(0).standard_normal(q.shape))
    import crmdata
    crmdata._table(db)
    # CRM columns name each well by its demo ID: unique, so they never resolve to a same-named well in another field.
    with db:  # CRM dataset in the pywaterflood layout: columns in well order, time in days
        db.execute("INSERT INTO crm_data VALUES(?,?,?,?,?,?,?,?,?,?,?)",
                   (FIELD, crmdata.current_version(db, FIELD) + 1, store.now(), SOURCE, json.dumps(["DEMO-ESP1", "DEMO-GL1", "DEMO-GL2"]),
                    json.dumps(["DEMO-I1", "DEMO-I2"]), json.dumps(t.tolist()), json.dumps(q.tolist()), json.dumps(inj.tolist()), None, None))
    f = pd.read_parquet(ROOT / "failure_1/dataset/processed_esp_data.parquet")
    test = f[(f.split == "test") & (f.cohort == "failed")]
    one = test[test.esp_id == test.esp_id.iloc[0]].sort_values("day_index")
    start = pd.Timestamp("2024-01-01")
    cols = dict(frequency_hz="raw_FRQ", discharge_psi="raw_PDP", intake_psi="raw_PIP", pump_avg_psi="raw_PAVG",
                motor_temp_f="raw_MT", esp_temp_f="raw_ESPT", current_a="raw_CURRENT", voltage_v="raw_VOLT")
    store.upsert_rows(db, wells["ESP1"], "esp_daily", [
        dict(date=(start + pd.Timedelta(days=int(r.day_index - one.day_index.min()))).strftime("%Y-%m-%d"),
             **{k: float(getattr(r, v)) for k, v in cols.items()}) for r in one.itertuples()], source=SOURCE)
    with np.load(ROOT / "pinn/dataset/BCS_data_train_limitado_f_zc_pm_pr_opera.npz") as z:
        n = min(1800, len(z["t"]))
        stamps = pd.date_range("2024-06-01", periods=n, freq="s", tz="UTC")
        x3 = z["x3"].ravel()
        store.upsert_rows(db, wells["ESP1"], "esp_fast", [
            dict(timestamp=stamps[i].isoformat(), frequency_hz=float(z["U"][i, 0]), choke_percent=float(z["U"][i, 1]),
                 manifold_bar=float(z["U"][i, 2]) / 1e5, reservoir_bar=float(z["U"][i, 3]) / 1e5,
                 bottomhole_bar=float(z["x1"].ravel()[i]) / 1e5, wellhead_bar=float(z["x2"].ravel()[i]) / 1e5,
                 test_m3h=float(x3[i]) * 3600 if i % 150 == 75 else None) for i in range(n)], source=SOURCE)
    # Gas-lift flow-meter telemetry: 6 hours at 60 s simulated by the gas_pinc plant with each well's own inputs.
    import gaslift
    from schema import SETTINGS
    for i, name in enumerate(("GL1", "GL2")):
        well = store.get_well(db, wells[name])
        settings = {x["key"]: json.loads(well["settings"]).get(x["key"], x.get("default")) for x in SETTINGS["gas_lift"]}
        rows = gaslift.simulate_telemetry(settings, "2024-06-01", samples=360, seed=i)
        store.upsert_rows(db, wells[name], "gl_fast", [{k: v for k, v in r.items() if k != "true_m3h"} for r in rows], source=SOURCE)
    tel = pd.read_csv(ROOT / "failure_2/dataset/synthetic/telemetry.csv")
    maint = pd.read_csv(ROOT / "failure_2/dataset/synthetic/maintenance.csv", dtype=str)
    for name, syn in zip(("GL1", "GL2"), sorted(tel.well_id.unique())[:2]):
        part = tel[tel.well_id == syn]
        store.upsert_rows(db, wells[name], "gl_pressure", [
            dict(timestamp=r.timestamp, casing_kpa=r.casing_pressure, tubing_head_kpa=r.tubing_head_pressure,
                 lift_gas_sm3d=None if pd.isna(r.lift_gas_rate) else r.lift_gas_rate,
                 choke_percent=None if pd.isna(r.choke_position) else r.choke_position) for r in part.itertuples()], source=SOURCE)
        events = []
        for r in maint[maint.well_id == syn].itertuples():
            when = next((v for v in (r.timestamp, getattr(r, "detected_at", None), getattr(r, "failed_at", None)) if isinstance(v, str) and v), None)
            if when:
                events.append(dict(timestamp=when, event_type=r.event_type, confirmed=(r.confirmed or None),
                                   event_id=getattr(r, "event_id", None) if isinstance(getattr(r, "event_id", None), str) else None))
        if events:
            store.upsert_rows(db, wells[name], "events", events, source=SOURCE)
    store.ensure_base(db, FIELD)
    base = db.execute("SELECT id FROM scenarios WHERE field=? ORDER BY created_at LIMIT 1", (FIELD,)).fetchone()["id"]
    store.save_scenario(db, dict(name="Base", notes="Demo facility limits", policy="hold", facility=dict(
        lift_gas_available_sm3d=400000, compressor_capacity_sm3d=450000, compressor_kwh_per_1000sm3=100,
        separator_liquid_m3d=9000, separator_gas_sm3d=700000, esp_power_kw=250, emissions_kg_per_kwh=0.4)), base)
    return {"field": FIELD, "wells": wells}


def remove(db):
    import crmdata
    crmdata._table(db)
    ids = [r["id"] for r in db.execute("SELECT id FROM wells WHERE field=?", (FIELD,))]
    with db:
        for wid in ids:
            db.execute("DELETE FROM results WHERE well_id=?", (wid,))
            db.execute("DELETE FROM versions WHERE well_id=?", (wid,))
        db.execute("DELETE FROM wells WHERE field=?", (FIELD,))
        db.execute("DELETE FROM runs WHERE field=?", (FIELD,))
        db.execute("DELETE FROM scenarios WHERE field=?", (FIELD,))
        db.execute("DELETE FROM crm_data WHERE field=?", (FIELD,))
    return {"removed": len(ids)}
